def chapter3(r: Report, assets: Path, metrics: dict):
    r.h1("Глава 3. МАТЕМАТИЧЕСКОЕ МОДЕЛИРОВАНИЕ И СТАТИСТИКА")

    r.h2("3.1. Постановка задачи статистики и реализация расчёта")
    r.p("Задача статистики — оценить динамику выдач и построить прогноз спроса на "
        "три месяца. Исходные данные — история выдач из таблицы Loans. "
        "DemandSeriesBuilder выбирает выдачи за 24 месяца, группирует их по году "
        "и месяцу и формирует непрерывный ряд, в котором отсутствующие месяцы "
        "представлены нулями.")
    r.p("Для ряда y1…yn и моментов времени t = 1…n коэффициенты линейной модели "
        "вычисляются методом наименьших квадратов:")
    f_b = r.formula("b = (Σ ti·yi − (Σ ti · Σ yi) / n) / (Σ ti² − (Σ ti)² / n),")
    f_a = r.formula("a = ȳ − b · t̄.")
    r.p(f"Формулы ({f_b}) и ({f_a}) дают свободный член и коэффициент наклона. "
        "Прогноз на k-й месяц вперёд определяется как")
    f_fc = r.formula("ŷn+k = a + b(n + k).")
    r.p(f"Качество модели оценивается средней абсолютной ошибкой и средней абсолютной "
        f"процентной ошибкой (формулы {f_fc} и далее):")
    f_mae = r.formula("MAE = (1/n) · Σ |yi − ŷi|,")
    f_mape = r.formula("MAPE = (100 % / n) · Σ |(yi − ŷi) / yi|,  yi > 0.")
    r.p(f"Показатели ({f_mae}) и ({f_mape}) позволяют сравнить модели между собой "
        "и оценить допустимость прогноза.")

    a = metrics["a"]
    b = metrics["b"]
    fc = metrics["forecast"]
    t_metrics = r.table(
        "Результаты прогнозирования по данным библиотеки",
        ["Показатель", "Значение"],
        [
            ("Свободный член a", _fmt(a)),
            ("Коэффициент b", _fmt(b) + " выдачи в месяц"),
            ("MAE", _fmt(metrics["mae"])),
            ("MAPE", _fmt(metrics["mape"], 1) + " %"),
            ("Прогноз на 1-й месяц", _fmt(fc[0], 1)),
            ("Прогноз на 2-й месяц", _fmt(fc[1], 1)),
            ("Прогноз на 3-й месяц", _fmt(fc[2], 1)),
        ],
        [7.0, 9.5],
    )
    r.p(f"По данным таблицы {t_metrics} коэффициент b близок к нулю и отрицателен: "
        "выраженного роста спроса нет. Высокое значение MAPE объясняется сильной "
        "сезонностью и месяцами с малым числом выдач (например, июль), когда даже "
        "небольшое отклонение даёт большой процент ошибки. Для практического "
        "планирования модель следует дополнить сезонными коэффициентами.")

# --------------------------------------------------------------------- source
TMP = HERE / "_source_copy.docx"
shutil.copyfile(ROOT / "Отчет_исходный.docx", TMP)
SRC = docx.Document(TMP)
SP = [" ".join(p.text.split()) for p in SRC.paragraphs]
ST = [[[c.text.strip() for c in row.cells] for row in t.rows] for t in SRC.tables]

FIGS: list[tuple[str, str]] = []
TABLES: list[tuple[str, str]] = []


def par(r: Report, *idx):
    for i in idx:
        r.p(SP[i])


def bullets(r: Report, *idx):
    for i in idx:
        r.bullet(SP[i].lstrip("–— ").strip())


def tasks(r: Report, *idx):
    for n, i in enumerate(idx, start=1):
        r.num(SP[i].split(")", 1)[1].strip(), n)


def src_table(r: Report, caption, tidx, widths, center_cols=(), font_size=11, label=None):
    rows = ST[tidx]
    number = r.table(caption, rows[0], rows[1:], widths, center_cols=center_cols,
                     font_size=font_size, label=label)
    TABLES.append((str(number), caption))
    return number


def fig(r: Report, image, caption, width=16.0, label=None):
    number = r.figure(image, caption, width_cm=width, label=label)
    FIGS.append((str(number), caption))
    return number


def next_table(r):
    return r.table_no + 1


def next_fig(r):
    return r.figure_no + 1


